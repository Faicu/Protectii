const L = require('./lib.js')
;(async () => {
  const s = await L.makeBot('Stranger')
  await L.pst('perm Stranger preciousstones.benefit.* true')
  await L.tp(s, 215, -60, 0)
  await L.sleep(5000)
  const r = await L.pst('move Stranger 201 -60 0')
  L.check('După restart: Entry Bouncer încă respinge', !/arrived 201/.test(r), r)
  await L.tp(s, 104, -60, 2)
  const b = await L.dig(s, 104, -61, 6)
  L.check('După restart: câmpul cumpărat de Victim încă protejează', /cancelled/.test(b), b)
  const m = await L.cmd('ps delete Owner', /Deleted Owner's (\d+) fields/)
  L.check('După restart: Owner are încă 9 câmpuri (8 + Translocator) în baza de date', m && m[1] === '9', m && m[0])
  const v = await L.cmd('ps delete Victim', /Deleted Victim's (\d+) fields/)
  L.check('După restart: Victim are câmpul cumpărat', v && v[1] === '1', v && v[0])
  s.quit(); setTimeout(() => process.exit(0), 300)
})()
